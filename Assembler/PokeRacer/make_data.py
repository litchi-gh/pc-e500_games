def spr(frames):
    w = len(frames[0][0])
    h = len(frames[0])
    assert h % 8 == 0
    b = bytearray([w, h // 8, len(frames), 1])
    for f in frames:
        assert len(f) == h, f
        for row in f:
            assert len(row) == w, (row, w)
        for r in range(h // 8):
            for x in range(w):
                col = [f[r * 8 + k][x] for k in range(8)]
                b.append(sum((c != ' ') << k for k, c in enumerate(col)))
                b.append(sum((c == '#') << k for k, c in enumerate(col)))
    return bytes(b)


