# コースの性格: 角の数、角のカーブ（最小、最大）、S 字の数、S 字のカーブ（最小、最大）、S 字の片側の角度（度）
STYLE = [
    (5, (20, 35), 14, (15, 30), (20, 40)),       # 海岸: ゆるく長い
    (6, (35, 60), 24, (35, 55), (30, 60)),       # 森: S 字が多い
    (4, (25, 45), 8, (20, 40), (20, 35)),        # 砂漠: 長いまっすぐ
    (4, (80, 95), 22, (70, 90), (40, 60)),       # 夜の街: 直角の角とクランク
    (7, (60, 95), 28, (55, 90), (40, 70)),       # 山: 短く急
    (6, (40, 65), 18, (35, 60), (30, 50)),       # 雪
    (5, (25, 55), 12, (25, 50), (25, 45)),       # 夕日
    (9, (50, 95), 26, (60, 95), (35, 65)),       # サーキット
]
MAP_W, MAP_H = 40, 16       # コースの図（左の計器の 2、3 行）
BAR = 38                    # 進み具合の段（0〜37。race.inc の bar_pos と同じ）
TURN = math.pi / (90 * 6000)   # 図の上で、カーブ 1 × 長さ 1 で曲がる角度（カーブ 90 を 6000 走ると半回転）
UNIT = 128                  # コースの表の長さの単位


def walk(segs):
    """区間の列をたどった終わりの点（右へ走り出す）"""
    x = y = a = 0.0
    for ln, c in segs:
        if c == 0:
            x += math.cos(a) * ln
            y += math.sin(a) * ln
            continue
        n = max(1, ln // 64)
        for _ in range(n):
            a += c * TURN * ln / n
            x += math.cos(a) * ln / n
            y += math.sin(a) * ln / n
    return x, y


def make_track(i):
    """ステージ i のコース: 1 周がステージの長さちょうどの周回路。[(長さ, カーブ)]
    右回りの角（合計 360°）で凸多角形を作り、辺には S 字を入れる。辺のまっすぐの長さは、
    周回路が閉じて、1 周がステージの長さになるように連立方程式で決める。"""
    import random
    rnd = random.Random(700 + i)
    n, (cmin, cmax), nw, (wmin, wmax), (bmin, bmax) = STYLE[i]
    lap = STAGES[i][4] * STAGES[i][8] * 256
    nw = max(2, round(nw * lap / 300000))                    # S 字の数はコースの長さに合わせる
    for _ in range(4000):
        if i == 3:
            angles = [math.pi / 2] * n                       # 夜の街は直角
        else:
            w = [rnd.uniform(0.6, 1.4) for _ in range(n)]
            angles = [2 * math.pi * v / sum(w) for v in w]
        sides = []                                           # 辺ごと: [S 字の列]、角
        for k in range(n):
            sides.append([])
        for _ in range(nw):
            sides[rnd.randrange(n)].append(None)
        fixed = []                                           # 長さが決まっている区間（角と S 字）
        plan = []                                            # (種類, 値): "st"=辺 k のまっすぐの 1 つ、"seg"=区間
        weights = []
        for k in range(n):
            pieces = len(sides[k]) + 1
            ws = [rnd.uniform(0.5, 1.5) for _ in range(pieces)]
            for p in range(pieces):
                plan.append(("st", (k, ws[p] / sum(ws))))
                if p < pieces - 1:
                    c = rnd.randint(wmin, wmax)
                    sgn = rnd.choice((-1, 1))
                    b = math.radians(rnd.randint(bmin, bmax))
                    ln = round(b / (c * TURN) / UNIT) * UNIT
                    plan.append(("seg", (ln, c * sgn)))
                    plan.append(("seg", (ln, -c * sgn)))
            c = rnd.randint(cmin, cmax)
            ln = round(angles[k] / (c * TURN) / UNIT) * UNIT
            plan.append(("seg", (ln, c)))
        # まっすぐを 0 にしてたどった終わり = 角と S 字だけでずれる分
        segs0 = [v if t == "seg" else (0, 0) for t, v in plan]
        vx, vy = walk(segs0)
        fixed_len = sum(v[0] for t, v in plan if t == "seg")
        # 辺 k の向き（その辺に入るときの向き。S 字は向きを変えない）
        heads = []
        a = 0.0
        for t, v in plan:
            if t == "st" and v[0] not in [h[0] for h in heads]:
                heads.append((v[0], a))
            if t == "seg":
                a += v[1] * TURN * v[0]
        u = {k: (math.cos(h), math.sin(h)) for k, h in heads}
        # 未知数: 辺ごとのまっすぐの合計 T_k。T_k を n - 3 本は乱数、3 本を解く
        free = list(range(n))
        rnd.shuffle(free)
        solve, given = free[:3], free[3:]
        rest = lap - fixed_len
        T = {k: rnd.uniform(0.6, 1.4) * rest / n for k in given}
        # Σ T_k u_k = -(vx, vy)、Σ T_k = rest
        bx = -vx - sum(T[k] * u[k][0] for k in given)
        by = -vy - sum(T[k] * u[k][1] for k in given)
        bs = rest - sum(T.values())
        A = [[u[k][0] for k in solve], [u[k][1] for k in solve], [1, 1, 1]]
        det = (A[0][0] * (A[1][1] * A[2][2] - A[1][2] * A[2][1]) - A[0][1] * (A[1][0] * A[2][2] - A[1][2] * A[2][0])
               + A[0][2] * (A[1][0] * A[2][1] - A[1][1] * A[2][0]))
        if abs(det) < 1e-6:
            continue
        sol = []
        for c in range(3):
            M = [row[:] for row in A]
            for r, bv in enumerate((bx, by, bs)):
                M[r][c] = bv
            d = (M[0][0] * (M[1][1] * M[2][2] - M[1][2] * M[2][1]) - M[0][1] * (M[1][0] * M[2][2] - M[1][2] * M[2][0])
                 + M[0][2] * (M[1][0] * M[2][1] - M[1][1] * M[2][0]))
            sol.append(d / det)
        for k, v in zip(solve, sol):
            T[k] = v
        minst = min(T[k] * min(v[1] for t, v in plan if t == "st" and v[0] == k) for k in range(n))
        if minst < UNIT * 8:
            continue
        track = []
        for t, v in plan:
            if t == "st":
                ln = round(T[v[0]] * v[1] / UNIT) * UNIT
                while ln > 0:
                    part = min(ln, 250 * UNIT)
                    track.append((part, 0))
                    ln -= part
            else:
                track.append(v)
        # 丸めで 1 周の長さがずれた分は最後のまっすぐで合わせる
        diff = lap - sum(ln for ln, _ in track)
        k = max(j for j, (ln, c) in enumerate(track) if c == 0)
        track[k] = (track[k][0] + round(diff / UNIT) * UNIT, 0)
        return track
    raise SystemExit(f"コース {i} が作れない")


