def to_screen(dots):
    b = bytearray(960)
    for y in range(32):
        for x in range(240):
            if dots[y][x]:
                b[(y // 8) * 240 + x] |= 1 << (y % 8)
    return bytes(b)


def title():
    dots = [[0] * 240 for _ in range(32)]
    text = "POKE RACER"
    adv = 17
    width = adv * len(text) + 7
    x0 = (240 - width) // 2
    for i, ch in enumerate(text):
        if ch == ' ':
            continue
        big = scale3x(glyph_px(ch), 5, 7)                 # 15 × 21
        for y in range(21):
            shear = (20 - y) // 3                          # 斜体
            for x in range(15):
                if big[y][x]:
                    X = x0 + i * adv + x + shear
                    if 0 <= X < 239 and y + 1 < 32:
                        dots[y + 1][X] = 1
    # 影（右下に 1 ドット、字の外だけ）
    shadow = [[0] * 240 for _ in range(32)]
    for y in range(31):
        for x in range(239):
            if dots[y][x] and not dots[y + 1][x + 1]:
                shadow[y + 1][x + 1] = 1
    # 字は黒く塗り、白い横線を 2 本通してレースの字らしくする。影は右下に 1 ドット
    logo = [[1 if (dots[y][x] and y not in (9, 15)) or shadow[y][x] else 0 for x in range(240)] for y in range(32)]
    # 両側の速さの線
    for y, (a, b) in zip((5, 9, 13, 17), ((0, 22), (4, 22), (0, 18), (6, 20))):
        for x in range(a, b):
            logo[y][x] = 1
            logo[y][239 - x] = 1
    # 下の帯（チェッカー模様）
    for x in range(240):
        logo[23][x] = (x // 2) % 2
    return to_screen(logo)


