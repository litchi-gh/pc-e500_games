def code_of(ch):
    o = ord(ch)
    assert 0x20 <= o <= 0x5F, ch
    return o


def font_small():
    """64 字 × 6 バイト（20h〜5Fh）"""
    b = bytearray(64 * 6)
    for ch, rows in G.items():
        i = code_of(ch) - 0x20
        for x in range(5):
            b[i * 6 + x] = sum((rows[y][x] == '#') << y for y in range(7))
    return bytes(b)


def italic(rows, h, slope):
    """上ほど右へずらす（斜体）。slope 行ごとに 1 ドット"""
    w = len(rows[0])
    sh = (h - 1) // slope
    out = []
    for y, r in enumerate(rows):
        s = (h - 1 - y) // slope
        out.append("." * s + r + "." * (sh - s))
    return out


def font_big():
    """64 字 × 24 バイト（12 × 16 の升、上の行 12 バイト、下の行 12 バイト）。斜体にして y = 1 から"""
    b = bytearray(64 * 24)
    for ch, rows in B.items():
        it = italic(rows, 14, 5)                       # 9 + 2 = 11 桁
        cell = [[0] * 12 for _ in range(16)]
        for y in range(14):
            for x in range(len(it[0])):
                cell[y + 1][x] = 1 if it[y][x] == '#' else 0
        i = code_of(ch) - 0x20
        for r in range(2):
            for x in range(12):
                b[i * 24 + r * 12 + x] = sum(cell[r * 8 + k][x] << k for k in range(8))
    return bytes(b)


def font_med():
    """計器の数字 11 字（0〜9、空白）× 9 桁 × 2 バイト（0、1 行）。斜体にして y = 4〜14"""
    b = bytearray()
    for ch in "0123456789 ":
        it = italic(MD[ch], 11, 4)                     # 7 + 2 = 9 桁
        for x in range(9):
            col = 0
            for y in range(11):
                if it[y][x] == '#':
                    col |= 1 << (y + 4)
            b += bytes((col & 0xFF, col >> 8))
    return bytes(b)


def badge(text, inverse=True):
    """札: 3 × 5 の字を 1 ドットおきに並べ、上下左右に 1 ドットの縁。黒地に白抜き（y = 0〜6、1 バイトずつ）"""
    cols = [0]
    for k, ch in enumerate(text):
        g = MINI[ch]
        for x in range(3):
            cols.append(sum((g[y][x] == '#') << (y + 1) for y in range(5)))
        cols.append(0)
    if inverse:
        cols = [0x7F ^ c for c in cols]
    return bytes(cols)


def glyph_px(ch, bold=False):
    rows = G[ch]
    px = [[1 if rows[y][x] == '#' else 0 for x in range(5)] for y in range(7)]
    if bold:   # 右へ 1 ドット太らせる（6 桁になる）
        px = [[px[y][x] if x < 5 else 0 for x in range(6)] for y in range(7)]
        px = [[px[y][x] | (px[y][x - 1] if x > 0 else 0) for x in range(6)] for y in range(7)]
    return px


def scale2x(px, w, h):
    """Scale2x（EPX）で 2 倍。px[y][x] = 0/1"""
    def p(x, y):
        return px[y][x] if 0 <= x < w and 0 <= y < h else 0
    o = [[0] * (w * 2) for _ in range(h * 2)]
    for y in range(h):
        for x in range(w):
            P, A, B_, C, D = p(x, y), p(x, y - 1), p(x + 1, y), p(x - 1, y), p(x, y + 1)
            o[y * 2][x * 2] = A if (C == A and C != D and A != B_) else P
            o[y * 2][x * 2 + 1] = B_ if (A == B_ and A != C and B_ != D) else P
            o[y * 2 + 1][x * 2] = C if (D == C and D != B_ and C != A) else P
            o[y * 2 + 1][x * 2 + 1] = D if (B_ == D and B_ != A and D != C) else P
    return o


def scale3x(px, w, h):
    """AdvMAME3x で 3 倍"""
    def p(x, y):
        return px[y][x] if 0 <= x < w and 0 <= y < h else 0
    o = [[0] * (w * 3) for _ in range(h * 3)]
    for y in range(h):
        for x in range(w):
            A, B_, C = p(x - 1, y - 1), p(x, y - 1), p(x + 1, y - 1)
            D, E, F = p(x - 1, y), p(x, y), p(x + 1, y)
            Gg, H, I = p(x - 1, y + 1), p(x, y + 1), p(x + 1, y + 1)
            e = [E] * 9
            if B_ != H and D != F:
                e[0] = D if D == B_ else E
                e[1] = B_ if (D == B_ and E != C) or (B_ == F and E != A) else E
                e[2] = F if B_ == F else E
                e[3] = D if (D == B_ and E != Gg) or (D == H and E != A) else E
                e[5] = F if (B_ == F and E != I) or (H == F and E != C) else E
                e[6] = D if D == H else E
                e[7] = H if (D == H and E != I) or (H == F and E != Gg) else E
                e[8] = F if H == F else E
            for k in range(9):
                o[y * 3 + k // 3][x * 3 + k % 3] = e[k]
    return o


