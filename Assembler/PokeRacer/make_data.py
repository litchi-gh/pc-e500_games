W = 256


def wave(x, terms, base):
    t = 2 * math.pi * x / W
    return base + sum(a * math.sin(t * k + p) for k, a, p in terms)


def sky_pack(dots):
    rows = [bytearray(W), bytearray(W)]
    for y in range(10):
        for x in range(W):
            if dots[y][x]:
                rows[y // 8][x] |= 1 << (y % 8)
    o = bytearray()
    for r in rows:
        o += r + r[:154]
    return bytes(o)


def blank():
    d = [[0] * W for _ in range(10)]
    for x in range(W):
        d[9][x] = 1
    return d


def sun(d, cx, cy, r, fill=0):
    for x in range(cx - 5, cx + 6):
        for y in range(0, 9):
            dd = math.hypot(x - cx, y - cy)
            if dd <= r + 0.5:
                d[y][x % W] = 1 if (dd > r - 0.7 or (fill and (x + y) % 2 == 0)) else 0


def cloud(d, cx, cy):
    for dx, dy in ((0, 0), (1, -1), (2, -1), (3, 0), (4, -1), (5, -1), (6, 0), (1, 1), (2, 1), (3, 1), (4, 1), (5, 1)):
        y = cy + dy
        if 0 <= y < 9:
            d[y][(cx + dx) % W] = 1


def sky_seaside():
    d = blank()
    for x in range(W):              # 海: 波の線
        if (x // 3) % 3 != 0:
            d[8][x] = 1
        if (x // 5 + 1) % 4 == 0:
            d[7][x] = 1
    for cx, w, h in ((30, 14, 3), (120, 8, 2), (200, 20, 4)):   # 島
        for x in range(cx - w, cx + w + 1):
            top = 8 - round(h * (1 - ((x - cx) / (w + 1)) ** 2))
            for y in range(top, 9):
                d[y][x % W] = 1 if y == top or (x + y) % 2 == 0 else 0
    sun(d, 70, 3, 2.6)
    for c in ((100, 1), (160, 2), (230, 1)):
        cloud(d, *c)
    return d


def sky_forest():
    d = blank()
    for x in range(W):
        h = wave(x, ((2, 1.4, 0.3), (5, 1.0, 1.2), (13, 0.6, 2.0)), 4.2)
        h = max(2, min(7, round(h + (1 if x % 4 < 2 else 0))))     # 木のてっぺんのぎざぎざ
        top = 8 - h
        d[top][x] = 1
        for y in range(top + 1, 9):
            d[y][x] = (x + y) % 2
    cloud(d, 60, 1)
    cloud(d, 180, 2)
    return d


def sky_desert():
    d = blank()
    for cx, w, h in ((20, 16, 5), (90, 10, 3), (150, 22, 6), (215, 8, 4)):   # 台地
        for x in range(cx - w, cx + w + 1):
            edge = min(x - (cx - w), (cx + w) - x)
            hh = h if edge >= 2 else max(1, h - (2 - edge) * 2)
            top = 8 - hh
            for y in range(top, 9):
                d[y][x % W] = 1 if y == top or x in (cx - w, cx + w) or (x + y) % 2 == 0 else 0
    sun(d, 120, 3, 3.2, fill=1)
    return d


def sky_night():
    d = [[1] * W for _ in range(10)]          # 黒い空
    for x in range(W):                        # 星
        if (x * 37) % 23 == 0:
            d[(x * 7) % 6][x] = 0
    for y in range(0, 7):                     # 三日月
        for x in range(44, 57):
            if math.hypot(x - 50, y - 3) <= 3.1:
                d[y][x] = 0 if math.hypot(x - 51.6, y - 2.4) > 2.3 else 1
    x = 0
    while x < W:                              # ビルの並び（白く抜いて、窓を黒く）
        w = 4 + (x * 13) % 7
        h = 2 + (x * 7) % 5
        for xx in range(x, min(W, x + w)):
            for y in range(8 - h, 9):
                inside = xx not in (x, x + w - 1) and y > 8 - h
                d[y][xx] = 1 if (inside and (xx + y) % 3 == 0) else 0
        x += w + 1
    for x in range(W):
        d[9][x] = 1
    return d


def sky_mountain():
    d = blank()
    for x in range(W):
        t = x % 64
        peak = 8.5 - abs(t - 32) / 5
        h = wave(x, ((4, 1.0, 0.7), (9, 0.8, 1.9)), 0) + peak
        h = max(2, min(9, round(h)))
        top = 9 - h
        snow = top + 2
        for y in range(top, 9):
            if y == top:
                d[y][x] = 1
            elif y < snow:
                d[y][x] = 0                      # 雪
            else:
                d[y][x] = (x + y) % 2
    cloud(d, 110, 1)
    return d


def sky_snow():
    d = blank()
    for x in range(W):                         # 雪の丘: 輪郭だけ（中は白）
        h = max(1, min(6, round(wave(x, ((2, 1.5, 0.9), (6, 0.9, 2.4)), 3.3))))
        d[8 - h][x] = 1
    for x in range(W):                         # 降る雪
        if (x * 29) % 7 == 0:
            d[(x * 5) % 7][x] = 1
    cloud(d, 40, 1)
    cloud(d, 170, 1)
    return d


def sky_sunset():
    d = blank()
    for x in range(W):                         # 海: 波
        if (x // 2) % 4 != 0:
            d[8][x] = 1
    cx = 128                                    # 水平線に沈む大きな夕日（下半分は海に隠れる）
    for x in range(cx - 9, cx + 10):
        for y in range(0, 9):
            dd = math.hypot(x - cx, (y - 8) * 1.2)
            if dd <= 8.5:
                d[y][x] = 1 if (dd > 7.6 or y % 2 == 0) else 0
    for dx in (-24, -16, 16, 24):               # 光の筋
        for k in range(6):
            x = cx + dx + (k if dx > 0 else -k) * 2
            d[7 - k][x % W] = 1
    for c in ((40, 2), (200, 1)):
        cloud(d, *c)
    return d


def sky_circuit():
    d = blank()
    x = 0
    while x < W:                               # 観客席: 屋根と、人の模様
        w = 20 + (x * 7) % 12
        for xx in range(x, min(W, x + w)):
            d[3][xx] = 1
            for y in range(4, 9):
                d[y][xx] = (xx + y) % 2 if y > 4 else 1
        x += w + 6
    for fx in range(10, W, 32):                # 旗
        for y in range(0, 4):
            d[y][fx] = 1
        for y in range(0, 2):
            for xx in range(fx + 1, fx + 4):
                d[y][xx % W] = (xx + y) % 2
    return d


