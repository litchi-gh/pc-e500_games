def course_path(track, length, step=32):
    """コースを length（進む量）だけたどった点の列。右へ走り出す"""
    pts = [(0.0, 0.0)]
    x = y = a = 0.0
    done = 0
    i = 0
    while done < length:
        seg_len, curve = track[i % len(track)]
        i += 1
        n = 0
        while n < seg_len and done < length:
            a += curve * TURN * step
            x += math.cos(a) * step
            y += math.sin(a) * step
            n += step
            done += step
            pts.append((x, y))
    return pts


def course_map(track, secs, cpd):
    """進み具合の段ごとの位置（38 × (x, y)、40 × 24 の中）と、確かめ用のドット"""
    length = secs * cpd * 256
    pts = course_path(track, length)
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    w = max(xs) - min(xs) or 1
    h = max(ys) - min(ys) or 1
    s = min((MAP_W - 4) / w, (MAP_H - 4) / h)
    ox = (MAP_W - w * s) / 2 - min(xs) * s
    oy = (MAP_H - h * s) / 2 - min(ys) * s

    def px(p):
        return (min(MAP_W - 1, max(0, round(p[0] * s + ox))), min(MAP_H - 1, max(0, round(p[1] * s + oy))))
    total = secs * cpd
    unit = total // (BAR - 1)
    where = []
    for b in range(BAR):
        d = min(total, b * unit) if b < BAR - 1 else total
        where.append(px(pts[min(len(pts) - 1, int(d * 256 / 32))]))
    # 確かめ用: 段の点を線でつないだ図（プログラムも同じように描く）
    dots = [[0] * MAP_W for _ in range(MAP_H)]

    def line(a, b):
        if abs(a[0] - b[0]) <= 1 and abs(a[1] - b[1]) <= 1:
            dots[b[1]][b[0]] = 1
            return
        m = ((a[0] + b[0]) // 2, (a[1] + b[1]) // 2)
        line(a, m)
        line(m, b)
    dots[where[0][1]][where[0][0]] = 1
    for k in range(1, BAR):
        line(where[k - 1], where[k])
    return bytes(v for p in where for v in p), dots


